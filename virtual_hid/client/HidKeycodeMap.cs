namespace VirtualHidClient;

/// <summary>
/// USB HID Usage Tables (Keyboard/Keypad Page 0x07, Consumer Page 0x0C) から
/// Windows Virtual-Key Code (winuser.h) への変換テーブル。
/// 標準的な104/109キー相当をカバー。未対応キーはfalseを返し無視する。
/// </summary>
public static class HidKeycodeMap
{
    private static readonly Dictionary<byte, ushort> KeyToVk = new()
    {
        // A-Z (0x04-0x1D)
        [0x04] = 0x41, [0x05] = 0x42, [0x06] = 0x43, [0x07] = 0x44, [0x08] = 0x45,
        [0x09] = 0x46, [0x0A] = 0x47, [0x0B] = 0x48, [0x0C] = 0x49, [0x0D] = 0x4A,
        [0x0E] = 0x4B, [0x0F] = 0x4C, [0x10] = 0x4D, [0x11] = 0x4E, [0x12] = 0x4F,
        [0x13] = 0x50, [0x14] = 0x51, [0x15] = 0x52, [0x16] = 0x53, [0x17] = 0x54,
        [0x18] = 0x55, [0x19] = 0x56, [0x1A] = 0x57, [0x1B] = 0x58, [0x1C] = 0x59,
        [0x1D] = 0x5A,

        // 1-9,0 (0x1E-0x27)
        [0x1E] = 0x31, [0x1F] = 0x32, [0x20] = 0x33, [0x21] = 0x34, [0x22] = 0x35,
        [0x23] = 0x36, [0x24] = 0x37, [0x25] = 0x38, [0x26] = 0x39, [0x27] = 0x30,

        [0x28] = 0x0D, // Enter -> VK_RETURN
        [0x29] = 0x1B, // Escape -> VK_ESCAPE
        [0x2A] = 0x08, // Backspace -> VK_BACK
        [0x2B] = 0x09, // Tab -> VK_TAB
        [0x2C] = 0x20, // Space -> VK_SPACE
        [0x2D] = 0xBD, // - -> VK_OEM_MINUS
        [0x2E] = 0xBB, // = -> VK_OEM_PLUS
        [0x2F] = 0xDB, // [ -> VK_OEM_4
        [0x30] = 0xDD, // ] -> VK_OEM_6
        [0x31] = 0xDC, // \ -> VK_OEM_5
        [0x33] = 0xBA, // ; -> VK_OEM_1
        [0x34] = 0xDE, // ' -> VK_OEM_7
        [0x35] = 0xC0, // ` -> VK_OEM_3
        [0x36] = 0xBC, // , -> VK_OEM_COMMA
        [0x37] = 0xBE, // . -> VK_OEM_PERIOD
        [0x38] = 0xBF, // / -> VK_OEM_2
        [0x39] = 0x14, // CapsLock -> VK_CAPITAL

        // F1-F12 (0x3A-0x45)
        [0x3A] = 0x70, [0x3B] = 0x71, [0x3C] = 0x72, [0x3D] = 0x73, [0x3E] = 0x74,
        [0x3F] = 0x75, [0x40] = 0x76, [0x41] = 0x77, [0x42] = 0x78, [0x43] = 0x79,
        [0x44] = 0x7A, [0x45] = 0x7B,

        [0x46] = 0x2C, // PrintScreen -> VK_SNAPSHOT
        [0x47] = 0x91, // ScrollLock -> VK_SCROLL
        [0x48] = 0x13, // Pause -> VK_PAUSE
        [0x49] = 0x2D, // Insert -> VK_INSERT
        [0x4A] = 0x24, // Home -> VK_HOME
        [0x4B] = 0x21, // PageUp -> VK_PRIOR
        [0x4C] = 0x2E, // Delete -> VK_DELETE
        [0x4D] = 0x23, // End -> VK_END
        [0x4E] = 0x22, // PageDown -> VK_NEXT
        [0x4F] = 0x27, // Right -> VK_RIGHT
        [0x50] = 0x25, // Left -> VK_LEFT
        [0x51] = 0x28, // Down -> VK_DOWN
        [0x52] = 0x26, // Up -> VK_UP

        [0x53] = 0x90, // NumLock -> VK_NUMLOCK
        [0x54] = 0x6F, // KP / -> VK_DIVIDE
        [0x55] = 0x6A, // KP * -> VK_MULTIPLY
        [0x56] = 0x6D, // KP - -> VK_SUBTRACT
        [0x57] = 0x6B, // KP + -> VK_ADD
        [0x58] = 0x0D, // KP Enter -> VK_RETURN (Windowsに専用VKは無い)
        [0x59] = 0x61, // KP 1 -> VK_NUMPAD1
        [0x5A] = 0x62, // KP 2 -> VK_NUMPAD2
        [0x5B] = 0x63, // KP 3 -> VK_NUMPAD3
        [0x5C] = 0x64, // KP 4 -> VK_NUMPAD4
        [0x5D] = 0x65, // KP 5 -> VK_NUMPAD5
        [0x5E] = 0x66, // KP 6 -> VK_NUMPAD6
        [0x5F] = 0x67, // KP 7 -> VK_NUMPAD7
        [0x60] = 0x68, // KP 8 -> VK_NUMPAD8
        [0x61] = 0x69, // KP 9 -> VK_NUMPAD9
        [0x62] = 0x60, // KP 0 -> VK_NUMPAD0
        [0x63] = 0x6E, // KP . -> VK_DECIMAL

        [0x65] = 0x5D, // Application(Menu) -> VK_APPS

        // F13-F24 (0x68-0x73)
        [0x68] = 0x7C, [0x69] = 0x7D, [0x6A] = 0x7E, [0x6B] = 0x7F, [0x6C] = 0x80,
        [0x6D] = 0x81, [0x6E] = 0x82, [0x6F] = 0x83, [0x70] = 0x84, [0x71] = 0x85,
        [0x72] = 0x86, [0x73] = 0x87,
    };

    private static readonly Dictionary<ushort, ushort> ConsumerToVk = new()
    {
        [0xE9] = 0xAF, // Volume Up -> VK_VOLUME_UP
        [0xEA] = 0xAE, // Volume Down -> VK_VOLUME_DOWN
        [0xE2] = 0xAD, // Mute -> VK_VOLUME_MUTE
        [0xCD] = 0xB3, // Play/Pause -> VK_MEDIA_PLAY_PAUSE
        [0xB5] = 0xB0, // Next Track -> VK_MEDIA_NEXT_TRACK
        [0xB6] = 0xB1, // Prev Track -> VK_MEDIA_PREV_TRACK
        [0xB7] = 0xB2, // Stop -> VK_MEDIA_STOP
    };

    public static bool TryGetVirtualKey(byte hidUsage, out ushort vk) => KeyToVk.TryGetValue(hidUsage, out vk);

    public static bool TryGetConsumerVirtualKey(ushort usageId, out ushort vk) => ConsumerToVk.TryGetValue(usageId, out vk);

    public static ushort ModifierVirtualKey(HidModifier modifier) => modifier switch
    {
        HidModifier.LeftCtrl => 0xA2,
        HidModifier.LeftShift => 0xA0,
        HidModifier.LeftAlt => 0xA4,
        HidModifier.LeftGui => 0x5B,
        HidModifier.RightCtrl => 0xA3,
        HidModifier.RightShift => 0xA1,
        HidModifier.RightAlt => 0xA5,
        HidModifier.RightGui => 0x5C,
        _ => throw new ArgumentOutOfRangeException(nameof(modifier)),
    };
}
